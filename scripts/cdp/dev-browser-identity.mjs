import { createHash } from "node:crypto"
import fs from "node:fs"
import os from "node:os"
import path from "node:path"

/**
 * Presentation and chrome state for the automation browser.
 *
 * Several debugging browsers can run side by side (shared profile, per-worktree
 * isolated profiles, other worktrees' instances) and every one of them otherwise
 * looks like a plain default-profile window. Chromium keeps everything that
 * tells them apart outside the profile's own data — the name, avatar and frame
 * tint in Local State, the pinned toolbar icons in Preferences — and only reads
 * it while starting, so the launcher writes it just before launching.
 */

/** Prefix marking a profile as one of this repo's automation browsers. */
const DEV_BROWSER_NAME_PREFIX = "AAH"

const SHARED_PROFILE_NAME = "dev-browser"
const DEFAULT_PROFILE_DIRECTORY = "Default"
const UNPACKED_EXTENSION_ID = /^[a-p]{32}$/u
/** Theme id of the frame tint installed by `--install-autogenerated-theme`. */
const AUTOGENERATED_THEME_ID = "autogenerated_theme_id"
/** Chromium's profile lock files: a Windows byte lock and a POSIX symlink. */
const LOCKFILE_NAME = "lockfile"
const SINGLETON_LOCK_NAME = "SingletonLock"

/**
 * Built-in avatar icons. Chromium's legacy illustrated set (`1`–`17`) is the
 * only one every Chromium build ships, so it is safe to pick from on any host.
 */
const AVATAR_ICON_RANGE = { first: 1, last: 17 }

/**
 * Frame accents, as the `r,g,b` triple the launcher passes to
 * `--install-autogenerated-theme`. Each one stays legible against both light
 * and dark tab strips.
 */
const ACCENT_COLORS = [
  "79,107,237",
  "14,148,136",
  "194,118,10",
  "179,58,168",
  "31,122,51",
  "63,91,139",
]

/**
 * Path bytes Chromium hashes for an unpacked extension's id: drive letter
 * upper-cased and separators normalized on Windows, otherwise unchanged.
 */
function toChromiumPath(extensionDir, windowsPath) {
  if (!windowsPath) return path.posix.resolve(extensionDir)

  const absolute = path.win32.isAbsolute(extensionDir)
    ? extensionDir
    : path.win32.resolve(extensionDir)
  return absolute
    .replace(/\//gu, "\\")
    .replace(/^([a-z])(?=:)/u, (drive) => drive.toUpperCase())
}

/**
 * The extension id Chromium derives for an unpacked extension: the first 16
 * bytes of SHA-256 over the path, with every hex digit shifted into `a`–`p`.
 * Knowing it before launch lets the launcher pin the extension it is about to
 * mount, without a browser round trip.
 */
export function deriveUnpackedExtensionId(extensionDir) {
  const windowsPath =
    os.platform() === "win32" ||
    (path.win32.isAbsolute(extensionDir) &&
      !path.posix.isAbsolute(extensionDir))
  const digest = createHash("sha256")
    .update(
      toChromiumPath(extensionDir, windowsPath),
      windowsPath ? "utf16le" : "utf8",
    )
    .digest("hex")
    .slice(0, 32)

  return digest.replace(
    /[0-9a-f]/gu,
    (digit) => "abcdefghijklmnop"[Number.parseInt(digit, 16)],
  )
}

/** FNV-1a over the profile directory, so one profile always looks the same. */
function hashProfileDir(profileDir) {
  const seed = typeof profileDir === "string" ? profileDir.toLowerCase() : ""
  let hash = 0x811c9dc5
  for (const character of seed) {
    hash ^= character.codePointAt(0) ?? 0
    hash = Math.imul(hash, 0x01000193) >>> 0
  }

  return hash
}

/** Stable frame accent for a profile, so a window keeps its color. */
function pickAccentColor(profileDir) {
  return (
    ACCENT_COLORS[hashProfileDir(profileDir) % ACCENT_COLORS.length] ??
    ACCENT_COLORS[0]
  )
}

/** Stable profile avatar for a profile; a different slice of the same hash. */
function pickAvatarIndex(profileDir) {
  const slots = AVATAR_ICON_RANGE.last - AVATAR_ICON_RANGE.first + 1
  return AVATAR_ICON_RANGE.first + ((hashProfileDir(profileDir) >>> 8) % slots)
}

/** Avatar resource Chromium expects for a built-in avatar index. */
function avatarIconReference(avatarIndex) {
  return `chrome://theme/IDR_PROFILE_AVATAR_${avatarIndex}`
}

/**
 * Name, avatar and frame tint for one browser instance. A shared profile gets a
 * name that does not change as worktrees take turns mounting their builds; an
 * isolated profile names the worktree whose build it serves.
 */
export function buildDevBrowserIdentity({
  profileDir,
  worktreeName,
  isolated,
}) {
  const worktree = typeof worktreeName === "string" ? worktreeName.trim() : ""
  const displayName =
    isolated && worktree
      ? `${DEV_BROWSER_NAME_PREFIX} ${worktree}`
      : `${DEV_BROWSER_NAME_PREFIX} ${SHARED_PROFILE_NAME}`

  return {
    displayName,
    accentColor: pickAccentColor(profileDir),
    avatarIndex: pickAvatarIndex(profileDir),
  }
}

/** Profile directory Chromium opens for this user data directory. */
export function resolveProfileDirectory(userDataDir) {
  let state
  try {
    state = readJsonFile(path.join(userDataDir, "Local State")).value
  } catch {
    // An unreadable state file still means the browser's default profile.
    return DEFAULT_PROFILE_DIRECTORY
  }
  const lastUsed = state?.profile?.last_used
  if (
    typeof lastUsed === "string" &&
    lastUsed.trim() &&
    // A recorded profile without a directory would open a fresh empty profile
    // and look like a lost session, so fall back to the default one.
    fs.existsSync(path.join(userDataDir, lastUsed))
  ) {
    return lastUsed
  }

  return DEFAULT_PROFILE_DIRECTORY
}

/**
 * Whether a browser currently holds this user data directory. Chromium locks it
 * for the lifetime of the process, and writing profile state under a running
 * browser is lost when that browser writes its own copy back on shutdown.
 */
export function isUserDataDirInUse(userDataDir, deps = {}) {
  const openFile = deps.openFile ?? ((file, flags) => fs.openSync(file, flags))
  const closeFile = deps.closeFile ?? ((handle) => fs.closeSync(handle))
  const readLink = deps.readLink ?? ((file) => fs.readlinkSync(file))
  const kill = deps.kill ?? ((pid) => process.kill(pid, 0))
  const hostname = deps.hostname ?? (() => os.hostname())

  try {
    const handle = openFile(path.join(userDataDir, LOCKFILE_NAME), "r+")
    try {
      closeFile(handle)
    } catch {
      /* the probe already answered */
    }
  } catch (error) {
    // Anything but "no lock file" means a browser holds the byte lock.
    if (error?.code !== "ENOENT") return true
  }

  try {
    // POSIX hosts leave a `<host>-<pid>` symlink; a stale one is not a lock.
    const target = String(readLink(path.join(userDataDir, SINGLETON_LOCK_NAME)))
    const separator = target.lastIndexOf("-")
    if (separator <= 0) return false
    // A lock on a shared filesystem may belong to another host; local process
    // enumeration cannot establish that the other browser has exited.
    if (target.slice(0, separator) !== hostname()) return true

    const pid = Number(target.slice(separator + 1))
    if (!Number.isInteger(pid) || pid <= 0) return false
    kill(pid)
    return true
  } catch (error) {
    // Only a missing/non-symlink lock or a definitely dead PID proves release.
    return !["ENOENT", "EINVAL", "ESRCH"].includes(error?.code)
  }
}

/** Poll until a closing browser releases the profile, or the budget runs out. */
export async function waitForUserDataDirRelease(
  userDataDir,
  { timeoutMs = 8000, intervalMs = 250 } = {},
  deps = {},
) {
  const deadline = Date.now() + timeoutMs
  for (;;) {
    if (!isUserDataDirInUse(userDataDir, deps)) return true
    if (Date.now() >= deadline) return false
    await new Promise((resolve) => setTimeout(resolve, intervalMs))
  }
}

/** Preparation summary for a launcher that cannot or will not brand. */
export function skippedDevBrowserPreparation(userDataDir, reason = undefined) {
  return {
    applied: false,
    reason,
    profileDirectory: resolveProfileDirectory(userDataDir),
    renamed: false,
    namePreserved: false,
    avatarIndex: undefined,
    pinnedExtensionIds: [],
    themeReserved: false,
  }
}

/**
 * Name and pin state for the browser about to be launched. Returns what it
 * changed so the caller can report it instead of guessing.
 */
export function prepareDevBrowserProfile(
  { userDataDir, identity, extensionIds = [] },
  deps = {},
) {
  const profileDirectory = resolveProfileDirectory(userDataDir)
  if (isUserDataDirInUse(userDataDir, deps)) {
    return skippedDevBrowserPreparation(userDataDir, "profile_in_use")
  }
  const summary = { ...skippedDevBrowserPreparation(userDataDir) }

  try {
    const { renamed, namePreserved, avatarIndex } = applyLocalStateIdentity(
      path.join(userDataDir, "Local State"),
      profileDirectory,
      identity,
    )
    const pinned = applyPreferences(
      path.join(userDataDir, profileDirectory, "Preferences"),
      extensionIds,
      avatarIndex,
    )
    return {
      ...summary,
      ...pinned,
      applied: true,
      renamed,
      namePreserved,
      avatarIndex,
    }
  } catch (error) {
    // An unreadable profile file is left untouched rather than replaced.
    return { ...summary, reason: error.message }
  }
}

/**
 * Name and avatar of the profile, which together identify the window in the
 * title bar, the profile card and the profile picker.
 */
function applyLocalStateIdentity(file, profileDirectory, identity) {
  const { value: current } = readJsonFile(file)
  const state = current ?? {}
  const before = JSON.stringify(state)
  const profile = (state.profile ??= {})
  const infoCache = (profile.info_cache ??= {})
  const entry = (infoCache[profileDirectory] ??= {})
  const name =
    typeof identity?.displayName === "string" ? identity.displayName.trim() : ""
  // A name the user set for their own purpose wins over the generated one; a
  // name this module wrote earlier stays ours so renames follow the worktree.
  const existingName = typeof entry.name === "string" ? entry.name : ""
  const nameCustomized =
    entry.is_using_default_name === false &&
    existingName.trim() !== "" &&
    !existingName.startsWith(`${DEV_BROWSER_NAME_PREFIX} `)

  let renamed = false
  if (name && !nameCustomized) {
    if (entry.name !== name || entry.is_using_default_name !== false) {
      entry.name = name
      entry.is_using_default_name = false
      renamed = true
    }
    if (!entry.shortcut_name && renamed) entry.shortcut_name = name
  }

  // Only built-in avatars from the legacy range are treated as ours, so an
  // avatar the user picked is never replaced on the next launch.
  const avatarIndex =
    typeof identity?.avatarIndex === "number" ? identity.avatarIndex : undefined
  const avatarCustomized =
    entry.is_using_default_avatar === false &&
    !isOwnAvatarIcon(entry.avatar_icon)
  if (avatarIndex !== undefined && !avatarCustomized) {
    entry.avatar_icon = avatarIconReference(avatarIndex)
    entry.is_using_default_avatar = false
  }

  if (!profile.last_used) profile.last_used = profileDirectory
  if (!profile.profiles_order?.includes?.(profileDirectory)) {
    profile.profiles_order = [
      ...(profile.profiles_order ?? []),
      profileDirectory,
    ]
  }

  writeJsonFile(file, state, before)
  return {
    renamed,
    namePreserved: nameCustomized,
    avatarIndex: avatarCustomized ? undefined : avatarIndex,
  }
}

/** Whether an avatar reference points at the built-in icons this module picks. */
function isOwnAvatarIcon(reference) {
  const match = /^chrome:\/\/theme\/IDR_PROFILE_AVATAR_(\d+)$/u.exec(
    typeof reference === "string" ? reference : "",
  )
  if (!match) return false

  const index = Number(match[1])
  return index >= AVATAR_ICON_RANGE.first && index <= AVATAR_ICON_RANGE.last
}

/** Pin the extension that is about to be mounted, keeping the user's own pins. */
function applyPreferences(file, extensionIds, avatarIndex) {
  const { value } = readJsonFile(file)
  const preferences = value ?? {}
  const before = JSON.stringify(preferences)
  const extensions = (preferences.extensions ??= {})
  const current = Array.isArray(extensions.pinned_extensions)
    ? extensions.pinned_extensions.filter((id) => typeof id === "string")
    : []
  const requested = extensionIds.filter(
    (id) => typeof id === "string" && UNPACKED_EXTENSION_ID.test(id),
  )
  const added = requested.filter((id) => !current.includes(id))

  const themeId = extensions.theme?.id
  const themeReserved =
    typeof themeId === "string" &&
    themeId !== "" &&
    themeId !== AUTOGENERATED_THEME_ID

  if (added.length > 0) {
    extensions.pinned_extensions = [...current, ...added]
  }
  if (typeof avatarIndex === "number") {
    preferences.profile = {
      ...(preferences.profile ?? {}),
      avatar_index: avatarIndex,
    }
  }
  writeJsonFile(file, preferences, before)

  return { pinnedExtensionIds: added, themeReserved }
}

/** Missing file means "no state yet"; unparsable state is never overwritten. */
function readJsonFile(file) {
  let raw
  try {
    raw = fs.readFileSync(file, "utf8")
  } catch {
    return { value: undefined, raw: undefined }
  }
  try {
    return { value: JSON.parse(raw), raw }
  } catch {
    throw new Error(`Unreadable profile file: ${file}`)
  }
}

/**
 * Chromium rewrites these files itself, so an unchanged value is left alone and
 * only the swap needs to be atomic.
 */
function writeJsonFile(file, value, previousSerialized) {
  const serialized = JSON.stringify(value)
  if (serialized === previousSerialized) return
  fs.mkdirSync(path.dirname(file), { recursive: true })
  const temporary = `${file}.aah-tmp`
  fs.writeFileSync(temporary, serialized)
  fs.renameSync(temporary, file)
}
