import { Eraser } from "lucide-react"
import { useMemo, useState } from "react"

import {
  ActionGroup,
  Alert,
  Button,
  Checkbox,
  ConfirmDialog,
  Modal,
} from "~/components/ui"
import { reloadRuntime } from "~/utils/browser/runtime"
import { isDevelopmentMode } from "~/utils/core/environment"
import { getErrorMessage } from "~/utils/core/error"

import { clearDevData, type DevDataCleanupScope } from "../dataCleanup"
import { useRegisterDevPanelSection } from "../DevPanelSectionsContext"
import type { DevPanelSection } from "../types"

/** Development-only saved data cleanup controls, separate from the general settings reset. */
export function DataCleanupSection() {
  const choices: readonly {
    id: DevDataCleanupScope
    label: string
    description: string
  }[] = [
    {
      id: "fixtures",
      label: "Test accounts and credentials",
      description:
        "Generated by DevPanel. Keeps manually added and imported data.",
    },
    {
      id: "accounts",
      label: "All accounts and credentials",
      description:
        "Every saved account, bookmark, credential, tag and check-in status. Keeps settings and history.",
    },
    {
      id: "history",
      label: "History and logs",
      description:
        "Verification, check-in, balance, usage, diagnostics and recent searches.",
    },
    {
      id: "caches",
      label: "Caches",
      description:
        "Site and sponsor catalogs, update checks and community resources. Rebuilt as needed.",
    },
    {
      id: "settings",
      label: "Settings",
      description:
        "Restore application preferences. Keeps analytics opt-out, accounts, credentials and history.",
    },
    {
      id: "all",
      label: "All saved extension data",
      description:
        "Remove every account, credential, setting, history, cache and scheduled task.",
    },
  ]
  const [open, setOpen] = useState(false)
  const [selected, setSelected] = useState<DevDataCleanupScope[]>([])
  const [confirmed, setConfirmed] = useState<DevDataCleanupScope[] | null>(null)
  const [working, setWorking] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const enabled = isDevelopmentMode()
  const section = useMemo<DevPanelSection | null>(
    () =>
      enabled
        ? {
            id: "data-cleanup",
            title: "Development data",
            category: "data",
            icon: Eraser,
            surfaces: ["options"],
            description:
              "Clear selected saved data in this development extension.",
            order: 90,
            actions: [
              {
                id: "open-data-cleanup",
                icon: Eraser,
                label: "Dev: Clear saved data",
                disabled: working,
                run: () => {
                  setSelected([])
                  setConfirmed(null)
                  setError(null)
                  setOpen(true)
                },
              },
            ],
          }
        : null,
    [enabled, working],
  )
  useRegisterDevPanelSection(section)

  if (!enabled) return null

  const clear = async () => {
    if (!confirmed || working) return
    setWorking(true)
    setError(null)
    try {
      await clearDevData(confirmed)
    } catch (cause) {
      setError(
        `Cleanup stopped. Some selected data may already have been removed. ${getErrorMessage(cause)}`,
      )
      setWorking(false)
      return
    }
    try {
      reloadRuntime({ throwOnError: true })
      setOpen(false)
      setConfirmed(null)
    } catch (cause) {
      setError(
        `Data was cleared, but the extension could not reload. Reload it manually. ${getErrorMessage(cause)}`,
      )
    } finally {
      setWorking(false)
    }
  }

  return (
    <>
      <Modal
        isOpen={open && !confirmed}
        onClose={() => setOpen(false)}
        title="Clear development data"
        header={
          <h2 className="text-foreground flex items-center gap-2 text-lg font-semibold">
            <Eraser className="text-muted-foreground size-5" />
            Clear development data
          </h2>
        }
        size="lg"
        footer={
          <ActionGroup layout="stack-on-narrow">
            <Button variant="outline" onClick={() => setOpen(false)}>
              {"Cancel"}
            </Button>
            <Button
              variant="destructive"
              disabled={selected.length === 0}
              onClick={() => setConfirmed([...selected])}
            >
              {"Review cleanup"}
            </Button>
          </ActionGroup>
        }
      >
        <div className="space-y-5">
          <div className="border-border bg-muted/30 rounded-lg border px-4 py-3">
            <p className="text-foreground text-sm font-medium">
              Choose what to reset
            </p>
            <p className="text-muted-foreground mt-1 text-xs leading-relaxed">
              Website logins and the Chrome profile stay untouched. Stop running
              tests and automatic sync first.
            </p>
          </div>
          <div className="space-y-5">
            {[
              {
                title: "Test fixtures",
                hint: "Reset generated scenarios",
                ids: ["fixtures"],
              },
              {
                title: "Saved accounts",
                hint: "Includes manually added and imported data",
                ids: ["accounts"],
              },
              {
                title: "History and preferences",
                hint: "Keep accounts while resetting local state",
                ids: ["history", "caches", "settings"],
              },
              {
                title: "Full reset",
                hint: "Permanently remove all saved extension data",
                ids: ["all"],
              },
            ].map((group) => (
              <fieldset
                key={group.title}
                className={
                  group.ids[0] === "all"
                    ? "border-destructive/30 rounded-xl border-2 px-4 pb-1"
                    : "border-border rounded-xl border px-4 pb-1"
                }
              >
                <legend
                  className={
                    group.ids[0] === "all"
                      ? "text-destructive px-2 text-sm font-semibold"
                      : "text-foreground px-2 text-sm font-semibold"
                  }
                >
                  {group.title}
                </legend>
                <p className="text-muted-foreground mt-1 mb-2 text-xs">
                  {group.hint}
                </p>
                <div className="divide-border divide-y">
                  {choices
                    .filter((choice) => group.ids.includes(choice.id))
                    .map((choice) => (
                      <label
                        key={choice.id}
                        htmlFor={`dev-cleanup-${choice.id}`}
                        className="hover:bg-muted/40 has-[[data-state=checked]]:bg-accent/50 -mx-2 flex cursor-pointer items-start gap-3 rounded-md px-2 py-3 transition-colors has-[:disabled]:cursor-default has-[:disabled]:opacity-50"
                      >
                        <Checkbox
                          id={`dev-cleanup-${choice.id}`}
                          aria-label={choice.label}
                          aria-describedby={`dev-cleanup-${choice.id}-description`}
                          className="mt-0.5"
                          checked={selected.includes(choice.id)}
                          disabled={
                            (choice.id !== "all" && selected.includes("all")) ||
                            (choice.id === "fixtures" &&
                              selected.includes("accounts"))
                          }
                          onCheckedChange={(checked) =>
                            setSelected((current) =>
                              checked
                                ? choice.id === "all"
                                  ? ["all"]
                                  : [
                                      ...current.filter(
                                        (id) =>
                                          choice.id !== "accounts" ||
                                          id !== "fixtures",
                                      ),
                                      choice.id,
                                    ]
                                : current.filter((id) => id !== choice.id),
                            )
                          }
                        />
                        <span className="min-w-0 space-y-1">
                          <span className="text-foreground block text-sm font-medium">
                            {choice.label}
                          </span>
                          <span
                            id={`dev-cleanup-${choice.id}-description`}
                            className="text-muted-foreground block text-xs leading-relaxed"
                          >
                            {choice.description}
                          </span>
                        </span>
                      </label>
                    ))}
                </div>
              </fieldset>
            ))}
          </div>
          <p className="text-muted-foreground border-border border-t pt-3 text-xs leading-relaxed">
            Chrome: enable Developer mode at chrome://extensions before cleanup.
            The extension reloads when finished.
          </p>
        </div>
      </Modal>
      <ConfirmDialog
        isOpen={Boolean(confirmed)}
        onClose={() => {
          if (!working) {
            setConfirmed(null)
            setError(null)
          }
        }}
        title={
          confirmed?.includes("all")
            ? "Clear all saved extension data?"
            : "Clear selected development data?"
        }
        description={
          "This cannot be undone. Website cookies and logins are preserved. The extension will reload after cleanup."
        }
        intent="destructive"
        confirmLabel={"Clear selected data and reload"}
        workingLabel={"Clearing…"}
        cancelLabel={"Back"}
        isWorking={working}
        onConfirm={() => void clear()}
        details={
          <div className="space-y-3">
            <ul className="list-disc space-y-1 pl-5 text-sm">
              {confirmed?.map((id) => (
                <li key={id}>
                  {choices.find((choice) => choice.id === id)?.label}
                </li>
              ))}
            </ul>
            {error ? (
              <Alert variant="destructive" role="alert" description={error} />
            ) : null}
          </div>
        }
      />
    </>
  )
}
